-- Four-eyes resolution of frozen payouts, durable links from retried keys to in-flight approvals,
-- and stable event ids for at-least-once approval callbacks.

CREATE TABLE payout_resolution (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approval_id      VARCHAR(64)              NOT NULL,
    open_approval_id VARCHAR(64),
    action           VARCHAR(16)              NOT NULL,
    transaction_id   VARCHAR(64),
    status           VARCHAR(16)              NOT NULL,
    proposed_by      VARCHAR(128)             NOT NULL,
    proposed_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    decided_by       VARCHAR(128),
    decided_at       TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_resolution_open_approval UNIQUE (open_approval_id),
    CONSTRAINT ck_resolution_action CHECK (action IN ('CONFIRM', 'RELEASE')),
    CONSTRAINT ck_resolution_status CHECK (status IN ('PROPOSED', 'APPLIED', 'REJECTED')),
    CONSTRAINT ck_resolution_open CHECK (
        (status = 'PROPOSED' AND open_approval_id = approval_id)
        OR (status <> 'PROPOSED' AND open_approval_id IS NULL)),
    CONSTRAINT ck_resolution_confirm_tx CHECK (action <> 'CONFIRM' OR transaction_id IS NOT NULL)
);
CREATE INDEX idx_resolution_approval ON payout_resolution (approval_id);

