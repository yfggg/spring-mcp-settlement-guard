-- Open reconciliation mismatches. open_approval_id is set only while the row is unresolved,
-- so the unique constraint keeps one open exception per approval.

CREATE TABLE payout_reconciliation_exception (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approval_id       VARCHAR(64)              NOT NULL,
    open_approval_id  VARCHAR(64),
    mismatch_code     VARCHAR(64)              NOT NULL,
    provider_state    VARCHAR(32)              NOT NULL,
    detail            VARCHAR(512)             NOT NULL,
    detected_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_recon_open_approval UNIQUE (open_approval_id)
);
CREATE INDEX idx_recon_approval ON payout_reconciliation_exception (approval_id);
