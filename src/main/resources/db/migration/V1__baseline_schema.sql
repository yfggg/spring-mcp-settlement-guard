-- Baseline schema. Portable across PostgreSQL 16 and H2 (PostgreSQL mode) used for local runs and CI.

CREATE TABLE settlement_invoice_item (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id                VARCHAR(64)    NOT NULL,
    order_id                VARCHAR(64)    NOT NULL,
    customer_email          VARCHAR(128)   NOT NULL,
    currency                VARCHAR(8)     NOT NULL,
    expected_amount         NUMERIC(18, 2) NOT NULL,
    captured_amount         NUMERIC(18, 2) NOT NULL,
    already_refunded_amount NUMERIC(18, 2) NOT NULL,
    CONSTRAINT uk_invoice_order_id UNIQUE (order_id)
);
CREATE INDEX idx_invoice_batch_id ON settlement_invoice_item (batch_id);

-- One lockable row per order; SELECT ... FOR UPDATE on this row serializes refund evaluation per order.
CREATE TABLE order_settlement_anchor (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       VARCHAR(64)              NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    last_locked_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_anchor_order_id UNIQUE (order_id)
);

CREATE TABLE idempotency_record (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(128)             NOT NULL,
    payload_hash    VARCHAR(64)              NOT NULL,
    state           VARCHAR(32)              NOT NULL,
    response_json   VARCHAR(2048),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_idempotency_state CHECK (state IN ('IN_PROGRESS', 'COMPLETED', 'UNKNOWN_SUSPENDED'))
);
CREATE INDEX idx_idempotency_state_updated ON idempotency_record (state, updated_at);

CREATE TABLE refund_approval_order (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approval_id        VARCHAR(64)              NOT NULL,
    order_id           VARCHAR(64)              NOT NULL,
    amount             NUMERIC(18, 2)           NOT NULL,
    currency           VARCHAR(8)               NOT NULL,
    reason_code        VARCHAR(64)              NOT NULL,
    idempotency_key    VARCHAR(128)             NOT NULL,
    snapshot_hash      VARCHAR(64)              NOT NULL,
    status             VARCHAR(32)              NOT NULL,
    internal_rule_code VARCHAR(64)              NOT NULL,
    transaction_id     VARCHAR(64),
    reviewer_id        VARCHAR(128),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    reviewed_at        TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_approval_id UNIQUE (approval_id),
    CONSTRAINT ck_approval_status CHECK (status IN (
        'PENDING_APPROVAL', 'EXECUTING', 'EXECUTED', 'PAYOUT_UNKNOWN', 'REJECTED', 'EXPIRED'))
);
CREATE INDEX idx_approval_order_window ON refund_approval_order (order_id, status, created_at);

CREATE TABLE tool_execution_audit_log (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_name       VARCHAR(80)              NOT NULL,
    caller_principal     VARCHAR(128)             NOT NULL,
    batch_id             VARCHAR(64),
    order_id             VARCHAR(64),
    approval_id          VARCHAR(64),
    amount               NUMERIC(18, 2),
    decision_status      VARCHAR(48)              NOT NULL,
    internal_policy_rule VARCHAR(80)              NOT NULL,
    reviewer_id          VARCHAR(128),
    duration_ms          BIGINT                   NOT NULL,
    llm_tokens_burned    INTEGER                  NOT NULL,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_audit_order_id ON tool_execution_audit_log (order_id);
CREATE INDEX idx_audit_approval_id ON tool_execution_audit_log (approval_id);
CREATE INDEX idx_audit_batch_id ON tool_execution_audit_log (batch_id);
