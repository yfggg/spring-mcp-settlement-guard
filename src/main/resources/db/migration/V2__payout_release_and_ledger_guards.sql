-- Manual resolution of frozen payouts, one approval per idempotency key,
-- and a ledger check that refunds cannot exceed the captured amount.

ALTER TABLE refund_approval_order DROP CONSTRAINT ck_approval_status;
ALTER TABLE refund_approval_order ADD CONSTRAINT ck_approval_status CHECK (status IN (
    'PENDING_APPROVAL', 'EXECUTING', 'EXECUTED', 'PAYOUT_UNKNOWN', 'PAYOUT_RELEASED', 'REJECTED', 'EXPIRED'));

ALTER TABLE refund_approval_order
    ADD CONSTRAINT uk_approval_idempotency_key UNIQUE (idempotency_key);

ALTER TABLE settlement_invoice_item
    ADD CONSTRAINT ck_refunded_within_captured
        CHECK (already_refunded_amount >= 0 AND already_refunded_amount <= captured_amount);

CREATE TABLE approval_event_outbox (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approval_id     VARCHAR(64)              NOT NULL,
    order_id        VARCHAR(64)              NOT NULL,
    amount          NUMERIC(18, 2)           NOT NULL,
    currency        VARCHAR(8)               NOT NULL,
    status          VARCHAR(32)              NOT NULL,
    transaction_id  VARCHAR(64),
    reviewer_id     VARCHAR(128),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at    TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_outbox_unpublished ON approval_event_outbox (published_at, created_at);
